import test from 'node:test';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openRelayStore} from '../../lib/storage/index.js';

test('通知状态只读查询定向与默认请求，固定批次目标，鉴权且不返回正文', async t => {
 const {createNotificationStatusRoutes,NOTIFICATION_STATUS_PATH}=await import('../../lib/services/notification-status.js');
 const dir=mkdtempSync(join(tmpdir(),'notify-status-'));
 let store=openRelayStore({dataDir:dir});
 t.after(()=>{store.close();rmSync(dir,{recursive:true,force:true})});
 const query=async(body,token='valid')=>createNotificationStatusRoutes({store,credentials:{verify:t=>t==='valid'}})[NOTIFICATION_STATUS_PATH](new Request('http://localhost'+NOTIFICATION_STATUS_PATH,{method:'POST',headers:{authorization:'Bearer '+token,'content-type':'application/json'},body:JSON.stringify(body)}));
 assert.equal((await query({request_id:'absent'},'wrong')).status,401);
 assert.equal((await query({request_id:'absent'})).status,404);
 assert.equal((await query({request_id:'absent',summary:'不得发送'})).status,400);
 store.targetedNotifications.insert({request_id:'target',agent:'codex',external_session_id:'source',dsh_session_id:'fixed',summary:'私密正文',result:'completed',external_ref:null},1);
 let result=await (await query({request_id:'target'})).json();
 assert.equal(result.delivery_status,'pending');assert.equal(result.dsh_session_id,'fixed');
 assert.equal(JSON.stringify(result).includes('私密正文'),false);
 store.targetedNotifications.claim('target');store.close();store=openRelayStore({dataDir:dir});store.targetedNotifications.recover();
 result=await (await query({request_id:'target'})).json();assert.equal(result.delivery_status,'unknown');assert.equal(result.attempts,1);
 store.targetedNotifications.finish('target','delivered',null);
 assert.equal((await (await query({request_id:'target'})).json()).delivery_status,'delivered');
 const route=store.bridge.ensure('claude','source','original');
 store.bridge.append(route,{id:'push:normal',kind:'push',body:'不应返回'},2);
 result=await (await query({request_id:'normal'})).json();assert.equal(result.delivery_status,'pending');
 const batch=store.bridge.prepare(route,null,3);
 store.bridge.bind(route.id,'changed');
 store.bridge.state(batch.id,'delivering',4);
 store.bridge.state(batch.id,'delivered',5);
 result=await (await query({request_id:'normal'})).json();assert.equal(result.dsh_session_id,'original');assert.equal(result.delivery_status,'delivered');
 store.bridge.acknowledge(batch.id,6);
 assert.equal((await (await query({request_id:'normal'})).json()).delivery_status,'processed');
 const before=JSON.stringify(store.bridge.event('push:normal'));
 await query({request_id:'normal'});assert.equal(JSON.stringify(store.bridge.event('push:normal')),before);
 store.bridge.append(route,{id:'push:muted',kind:'push',body:'被屏蔽'},7);store.bridge.mute(route.id,true);
 assert.equal((await (await query({request_id:'muted'})).json()).delivery_status,'muted');
});

test('dsh-notify --status 经 HTTP 只读查询，不接受发送参数或重复参数', async t => {
 const {createNotificationStatusRoutes}=await import('../../lib/services/notification-status.js');
 const {createPushServer}=await import('../../lib/services/push.js');
 const {writeFileSync}=await import('node:fs');
 const {execFile}=await import('node:child_process');
 const {promisify}=await import('node:util');
 const dir=mkdtempSync(join(tmpdir(),'notify-status-cli-'));const store=openRelayStore({dataDir:dir});
 t.after(()=>{store.close();rmSync(dir,{recursive:true,force:true})});
 const token='T'.repeat(43);
 store.targetedNotifications.insert({request_id:'original',agent:'codex',external_session_id:'source',dsh_session_id:'fixed',summary:'私密正文',result:'completed',external_ref:null},1);
 let sends=0;
 const server=createPushServer({port:0,handler:async()=>{sends++;return new Response('不应发送',{status:500})},routes:createNotificationStatusRoutes({store,credentials:{verify:t=>t===token}})});
 const {port}=await server.start();t.after(()=>server.stop());
 const config=join(dir,'config.json');writeFileSync(config,JSON.stringify({token,endpoint:`http://127.0.0.1:${port}/api/agent-relay/notifications`}));
 const script=fileURLToPath(new URL('../../skills/dsh-notify/send.mjs',import.meta.url));
 const run=args=>promisify(execFile)(process.execPath,[script,...args],{env:{...process.env,DSH_AGENT_RELAY_CONFIG:config}});
 const args=['--status','--request-id','original'];
 const result=JSON.parse((await run(args)).stdout);assert.equal(result.delivery_status,'pending');assert.equal(result.request_id,'original');
 assert.ok(!JSON.stringify(result).includes(token));assert.ok(!JSON.stringify(result).includes('私密正文'));
 await assert.rejects(run([...args,'--summary','不能发送']),/查询/);
 await assert.rejects(run([...args,'--request-id','other']),/重复/);
 await assert.rejects(run(['--status','--request-id','missing']),/未找到|不支持/);
 assert.equal(sends,0);assert.equal(store.targetedNotifications.get('original').attempts,0);
});
